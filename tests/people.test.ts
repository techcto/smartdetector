test('matching requires model identity, separation, full coverage and explicit calibration before muting',()=>{
 const gallery=[{id:'member',version:1,name:'Member',family:true,saveActivity:false,recognize:true,notify:false,enrolled:true,createdAt:'',reference:{modelId:model,embedding}}];
 const frames=[{at_ms:0,detections:[{label:'person',source:'opencv' as const,advisory:false,box:{x:0.1,y:0,width:0.8,height:1}}]}];
 const policy={threshold:0.75,margin:0.1,calibrated:true};
 assert.equal(matchFaces(measurement,gallery,frames,policy).notify,false);
 assert.equal(matchFaces(measurement,gallery,frames,{...policy,calibrated:false}).notify,true);
 assert.equal(matchFaces({...measurement,model_id:model+'changed'},gallery,frames,policy).notify,true);
 assert.equal(matchFaces(measurement,[...gallery,{...gallery[0],id:'similar'}],frames,policy).notify,true);
 assert.equal(matchFaces(measurement,gallery,[{at_ms:0,detections:[]}],policy).notify,true);
 assert.equal(matchFaces(measurement,gallery,[{at_ms:0,detections:[...frames[0].detections,{...frames[0].detections[0],label:'fire'}]}],policy).notify,true);
 assert.equal(matchFaces(measurement,gallery,frames,policy).sightings.length,0);
 assert.throws(()=>validateFaceResult({...measurement,frames:[{at_ms:0,faces:[{...measurement.frames[0].faces[0],embedding:[NaN]}]}]}));
});
