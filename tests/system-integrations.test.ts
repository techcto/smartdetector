import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createHmac} from 'node:crypto';
import {NextRequest} from 'next/server';
import {GET,POST} from '../src/app/api/v1/admin/integrations/[provider]/route';
import {saveSystemIntegration,systemIntegration,publicSystemIntegration} from '../src/lib/system-integrations';
import {createSession,sessionCookie} from '../src/lib/session';
import {store} from '../src/lib/store';
import {connectionCredentials,removeSetting} from '../src/lib/providers';
import {receiveRingCode,completeSystemRingLink,ringDestination} from '../src/lib/ring-link';
test('system settings require root, reject CSRF, redact and preserve secrets',async()=>{
 const secret=process.env.SMARTDETECTOR_SESSION_SECRET='synthetic-system-admin-secret-long-enough';
 const token=await createSession({id:'root',username:'root',role:'root',orgId:'test',expiresAt:Date.now()+60000},secret);
 const context={params:Promise.resolve({provider:'ring'})};
 const request=(method:string,origin='https://test.example',body?:unknown)=>new NextRequest('https://test.example/api/v1/admin/integrations/ring',{method,headers:{host:'test.example',origin,cookie:sessionCookie+'='+token,'Content-Type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});
 assert.equal((await GET(new NextRequest('https://test.example'),context)).status,403);
 assert.equal((await POST(request('POST','https://wrong.example',{}),context)).status,403);
 assert.equal((await POST(request('POST',undefined,{clientId:'test-client',clientSecret:'test-secret',hmacKey:'test-hmac'}),context)).status,200);
 const result=await(await GET(request('GET'),context)).json();assert.equal(result.settings.clientSecret,true);assert.equal(JSON.stringify(result).includes('test-secret'),false);
 await saveSystemIntegration('ring',{clientSecret:''});assert.equal((await systemIntegration('ring')).clientSecret,'test-secret');
 await assert.rejects(saveSystemIntegration('bedrock',{region:'bad'}));
 await assert.rejects(saveSystemIntegration('bedrock',{accessKeyId:'forbidden'}));
 await saveSystemIntegration('alexa',{skillId:'test-skill',clientSecret:'alexa-secret'});assert.equal((await publicSystemIntegration('alexa')).clientSecret,true);
});
test('shared Ring callbacks bind account to one location and release on disconnect',async()=>{
 process.env.SMARTDETECTOR_SESSION_SECRET='synthetic-system-admin-secret-long-enough';
 await saveSystemIntegration('ring',{clientId:'test-client',clientSecret:'test-secret',hmacKey:'test-hmac'});
 const a=await store.createOrganization({name:'A',ownerId:'test',orgType:'business'}),b=await store.createOrganization({name:'B',ownerId:'test',orgType:'business'});
 const mock=(async()=>new Response(JSON.stringify({access_token:'access',refresh_token:'refresh',expires_in:3600,data:{id:'account'}}),{status:200}))as typeof fetch;
 const time=String(Date.now()),nonce=createHmac('sha256','test-hmac').update(time+':account').digest('base64url');
 await receiveRingCode('SYSTEM','APP','code',mock);
 await assert.rejects(completeSystemRingLink(a.id,'test','bad',time,mock));
 const id=await completeSystemRingLink(a.id,'test',nonce,time,mock);
 assert.deepEqual(await ringDestination('account'),{orgId:a.id,connectionId:id});
 assert.equal((await connectionCredentials(a.id,id,'ring'))?.accessToken,'access');
 assert.equal(await connectionCredentials(b.id,id,'ring'),null);
 await assert.rejects(completeSystemRingLink(a.id,'test',nonce,time,mock));
 await receiveRingCode('SYSTEM','APP','fresh-code',mock);
 await assert.rejects(completeSystemRingLink(b.id,'test',nonce,time,mock));
 await removeSetting(a.id,id);assert.equal(await ringDestination('account'),null);
 const otherId=await completeSystemRingLink(b.id,'test',nonce,time,mock);assert.equal((await ringDestination('account'))?.connectionId,otherId);
});
